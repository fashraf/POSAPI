/*==============================================================================
  Nazad POS — 001 · Schema (PostgreSQL 16)

  Every table, key, check, index and sequence of a tenant database, plus the
  row types that procedures take as lists. Generated from the final SQL Server
  schema (all migrations through 023) when the platform moved to PostgreSQL,
  then kept by hand.

  Conventions — see README.md:
    * Names are written unquoted in PascalCase and fold to lower case, so
      SELECT SaleId FROM sales.Sale works as written and Dapper maps saleid
      back onto SaleId.
    * Short text is varchar COLLATE ci: case-insensitive, accent-sensitive,
      like the Arabic_CI_AS collation the SQL Server database used. Equality,
      uniqueness, GROUP BY and ORDER BY behave as they did. LIKE, ILIKE,
      regular expressions, replace() and strpos() refuse a nondeterministic
      collation: write  Col COLLATE "default" ILIKE @Pattern.
    * Timestamps are timestamp(3) holding UTC, as DATETIME2 did; "now" is
      (now() AT TIME ZONE 'utc').
    * Money is bigint halalas; booleans are boolean.
==============================================================================*/

/* Case-insensitive, accent-sensitive: "Ahmed" = "AHMED", "e" <> "é". */
