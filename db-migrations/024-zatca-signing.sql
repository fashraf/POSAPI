/*
  024 — ZATCA Phase 2 signing: one EGS unit per branch, and the signed
  documents it issues.

  zatca.EgsUnit
    A branch's e-invoice generation unit: its certificate (CSID), its
    private key and CSID secret (encrypted by the API with a key that is
    never in this database), and the head of its chain: LastIcv and
    LastHash, the 88-character chain value of the last document signed.
    A branch with an active unit signs every sale and credit note made from
    ActivatedAtUtc on; one without keeps printing the Phase 1 QR (022).
    The chain belongs to the unit, so a renewed certificate carries on
    from the same head.

  zatca.Document
    Every signed document, append-only: the exact XML that was signed
    (kept for the six years the VAT rules require), its counter, hash and
    the hash it chained from, and the reporting fields the reporting worker
    uses. A signed document is never edited or deleted (trigger below); a
    correction is a new credit or debit note.

  sales.Sale.ZatcaCounter was unique across the tenant. The counter belongs
  to a branch's chain, so it is unique per branch.
*/

CREATE SCHEMA IF NOT EXISTS zatca;

CREATE TABLE IF NOT EXISTS zatca.EgsUnit (
    BranchId            varchar(40) COLLATE ci NOT NULL,
    /* test: a self-signed certificate (development only, never reported);
       simulation / core: ZATCA's two gateways. */
    Environment         varchar(12) COLLATE ci NOT NULL,
    Status              varchar(12) COLLATE ci NOT NULL DEFAULT 'active',
    CertificateBase64   text NOT NULL,
    CertificateNotAfter timestamp(3) NULL,
    PrivateKeyCt        text NOT NULL,
    SecretCt            text NULL,
    KekId               varchar(40) COLLATE ci NOT NULL,
    LastIcv             bigint NOT NULL DEFAULT 0,
    LastHash            varchar(100) COLLATE ci NOT NULL
        DEFAULT 'NWZlY2ViNjZmZmM4NmYzOGQ5NTI3ODZjNmQ2OTZjNzljMmRiYzIzOWRkNGU5MWI0NjcyOWQ3M2EyN2ZiNTdlOQ==',
    ActivatedAtUtc      timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CreatedAtUtc        timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    UpdatedAtUtc        timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    CONSTRAINT PK_EgsUnit PRIMARY KEY (BranchId),
    CONSTRAINT FK_EgsUnit_Branch FOREIGN KEY (BranchId) REFERENCES core.Branch (BranchId),
    CONSTRAINT CK_EgsUnit_Environment CHECK (Environment IN ('test', 'simulation', 'core')),
    CONSTRAINT CK_EgsUnit_Status CHECK (Status IN ('active', 'suspended', 'retired')),
    CONSTRAINT CK_EgsUnit_Icv CHECK (LastIcv >= 0)
);

CREATE TABLE IF NOT EXISTS zatca.Document (
    DocumentId          bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    BranchId            varchar(40) COLLATE ci NOT NULL,
    Icv                 bigint NOT NULL,
    Kind                varchar(12) COLLATE ci NOT NULL,
    Simplified          boolean NOT NULL,
    SaleId              varchar(40) COLLATE ci NULL,
    ReturnId            varchar(40) COLLATE ci NULL,
    DocumentNumber      varchar(40) COLLATE ci NOT NULL,
    Uuid                uuid NOT NULL,
    InvoiceHash         varchar(60) COLLATE ci NOT NULL,
    PreviousHash        varchar(100) COLLATE ci NOT NULL,
    QrPayload           varchar(1000) COLLATE ci NOT NULL,
    SignedXml           text NOT NULL,
    Environment         varchar(12) COLLATE ci NOT NULL,
    IssuedAtUtc         timestamp(3) NOT NULL,
    SignedAtUtc         timestamp(3) NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
    /* Reporting (simplified) or clearance (standard), worked by the API. */
    ReportingStatus     varchar(24) COLLATE ci NOT NULL DEFAULT 'pending',
    Attempts            integer NOT NULL DEFAULT 0,
    NextAttemptAtUtc    timestamp(3) NULL,
    DeadlineAtUtc       timestamp(3) NOT NULL,
    ReportedAtUtc       timestamp(3) NULL,
    LastHttpStatus      integer NULL,
    Messages            jsonb NULL,
    CONSTRAINT PK_ZatcaDocument PRIMARY KEY (DocumentId),
    CONSTRAINT FK_ZatcaDocument_Unit FOREIGN KEY (BranchId) REFERENCES zatca.EgsUnit (BranchId),
    CONSTRAINT FK_ZatcaDocument_Sale FOREIGN KEY (SaleId) REFERENCES sales.Sale (SaleId),
    CONSTRAINT FK_ZatcaDocument_Return FOREIGN KEY (ReturnId) REFERENCES sales.SaleReturn (ReturnId),
    CONSTRAINT UQ_ZatcaDocument_Icv UNIQUE (BranchId, Icv),
    CONSTRAINT UQ_ZatcaDocument_Uuid UNIQUE (Uuid),
    CONSTRAINT CK_ZatcaDocument_Kind CHECK (Kind IN ('invoice', 'credit_note', 'debit_note')),
    CONSTRAINT CK_ZatcaDocument_Source CHECK (
        (Kind = 'invoice' AND SaleId IS NOT NULL AND ReturnId IS NULL)
        OR (Kind = 'credit_note' AND ReturnId IS NOT NULL)
        OR Kind = 'debit_note'),
    CONSTRAINT CK_ZatcaDocument_Status CHECK (ReportingStatus IN
        ('pending', 'not_reported', 'reported', 'reported_with_warnings', 'cleared',
         'cleared_with_warnings', 'rejected', 'retrying', 'blocked'))
);

/* One signed invoice per sale, one signed note per return. */
CREATE UNIQUE INDEX IF NOT EXISTS UX_ZatcaDocument_Sale ON zatca.Document (SaleId) WHERE Kind = 'invoice';
CREATE UNIQUE INDEX IF NOT EXISTS UX_ZatcaDocument_Return ON zatca.Document (ReturnId) WHERE ReturnId IS NOT NULL;
CREATE INDEX IF NOT EXISTS IX_ZatcaDocument_Queue ON zatca.Document (ReportingStatus, NextAttemptAtUtc)
    WHERE ReportingStatus IN ('pending', 'retrying');

/* What was signed stays as it was signed. */
CREATE OR REPLACE FUNCTION zatca.trg_Document_Immutable()
RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'A signed ZATCA document is never deleted.' USING DETAIL = '69001';
    END IF;

    IF NEW.SignedXml IS DISTINCT FROM OLD.SignedXml
       OR NEW.InvoiceHash IS DISTINCT FROM OLD.InvoiceHash
       OR NEW.PreviousHash IS DISTINCT FROM OLD.PreviousHash
       OR NEW.Icv IS DISTINCT FROM OLD.Icv
       OR NEW.Uuid IS DISTINCT FROM OLD.Uuid
       OR NEW.BranchId IS DISTINCT FROM OLD.BranchId
       OR NEW.Kind IS DISTINCT FROM OLD.Kind
       OR NEW.SaleId IS DISTINCT FROM OLD.SaleId
       OR NEW.ReturnId IS DISTINCT FROM OLD.ReturnId
       OR NEW.DocumentNumber IS DISTINCT FROM OLD.DocumentNumber
       OR NEW.QrPayload IS DISTINCT FROM OLD.QrPayload
       OR NEW.IssuedAtUtc IS DISTINCT FROM OLD.IssuedAtUtc THEN
        RAISE EXCEPTION 'A signed ZATCA document cannot be changed. Issue a credit or debit note.' USING DETAIL = '69002';
    END IF;

    RETURN NEW;
END $$;

DROP TRIGGER IF EXISTS TR_ZatcaDocument_Immutable ON zatca.Document;
CREATE TRIGGER TR_ZatcaDocument_Immutable
    BEFORE UPDATE OR DELETE ON zatca.Document
    FOR EACH ROW EXECUTE FUNCTION zatca.trg_Document_Immutable();

/* The counter is a branch's chain position. */
DROP INDEX IF EXISTS sales.UX_Sale_ZatcaCounter;
CREATE UNIQUE INDEX IF NOT EXISTS UX_Sale_BranchZatcaCounter ON sales.Sale (BranchId, ZatcaCounter)
    WHERE ZatcaCounter IS NOT NULL;

/* A credit note's own QR (the sale's is on sales.Sale). */
ALTER TABLE sales.SaleReturn ADD COLUMN IF NOT EXISTS ZatcaQrPayload varchar(1000) COLLATE ci NULL;
